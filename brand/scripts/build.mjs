const BRAND = join(dirname(fileURLToPath(import.meta.url)), "..");
const PKG = join(BRAND, "..");
const T = JSON.parse(readFileSync(join(BRAND, "tokens/tokens.json"), "utf8"));
const CHECK_ONLY = process.argv.includes("--check");
const HEADER = "GENERATED by brand/scripts/build.mjs from brand/tokens/tokens.json — do not edit.";

// ---------------------------------------------------------------- resolution
const PRODUCTS = Object.keys(T.products);
const MODES = ["light", "dark"];

/** Resolve a token ref to {hex, alpha}. Forms: "#RRGGBB", "ink.900", "@600" (product scale), any + "/NN" alpha %. */
function resolve(ref, scale) {
  let [base, a] = String(ref).split("/");
  const alpha = a === undefined ? 1 : Number(a) / 100;
  if (base.startsWith("#")) return { hex: base.toUpperCase(), alpha };
  if (base.startsWith("@")) base = `${scale}.${base.slice(1)}`;
  const [fam, step] = base.split(".");
  const hex = T.palette[fam]?.[step];
  if (!hex) throw new Error(`Unknown color ref "${ref}" (scale ${scale})`);
  return { hex: hex.toUpperCase(), alpha };
}
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const cssColor = ({ hex, alpha }) =>
  alpha === 1 ? hex : `rgb(${rgb(hex).join(" ")} / ${+(alpha * 100).toFixed(1)}%)`;
const argb = ({ hex, alpha }) =>
  "0x" + Math.round(alpha * 255).toString(16).padStart(2, "0").toUpperCase() + hex.slice(1);
const camel = (s) => s.replace(/[-.](\w)/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
const stepName = (s) => String(s).replace(".", "_");

/** "&key" refs read a product-level token (e.g. "&accent" -> products.seller.accent). */
const productRef = (v, product) => (String(v).startsWith("&") ? T.products[product][v.slice(1)] : v);

function semantic(product, mode) {
  const scale = T.products[product].scale;
  return Object.fromEntries(
    Object.entries(T.semantic[mode]).map(([k, v]) => [k, resolve(productRef(v, product), scale)]),
  );
}
const DEFAULT_SCALE = T.products.consumer.scale;
const gradStops = (product) => T.products[product].gradient.map((c) => resolve(c, T.products[product].scale));
/** CSS angle -> start/end unit points (x right, y down). 90deg = left->right, 135deg = top-left->bottom-right. */
function gradPoints(angle) {
  const a = ((angle - 90) * Math.PI) / 180;
  const dx = +Math.cos(a).toFixed(3), dy = +Math.sin(a).toFixed(3);
  return { from: [-dx, -dy], to: [dx, dy] };
}

// ---------------------------------------------------------------- contrast (WCAG 2.2)
function lum(hex) {
  return rgb(hex)
    .map((c) => c / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    .reduce((acc, c, i) => acc + c * [0.2126, 0.7152, 0.0722][i], 0);
}
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

let failures = 0;
const report = [];
for (const p of PRODUCTS) {
  for (const m of MODES) {
    const s = semantic(p, m);
    for (const [fg, bg, min] of T.contrastChecks) {
      const r = contrast(s[fg].hex, s[bg].hex);
      const ok = r >= min;
      if (!ok) failures++;
      report.push({ product: p, mode: m, pair: `${fg} on ${bg}`, ratio: +r.toFixed(2), min, ok });
    }
  }
}
for (const r of report.filter((x) => !x.ok)) {
  console.error(`✗ ${r.product}/${r.mode}: ${r.pair} = ${r.ratio} (needs ${r.min})`);
}
console.log(`contrast: ${report.length - failures}/${report.length} pairs pass WCAG targets`);
if (failures) process.exit(1);
if (CHECK_ONLY) process.exit(0);

// ---------------------------------------------------------------- helpers
const out = (rel, text) => {
  const f = join(PKG, rel);
  mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, text);
  console.log("wrote", rel);
};
const productScaleSteps = Object.keys(T.palette.violet);
const fontStack = (k) => `'${T.font[k].family}', ${T.font[k].fallback}`;
const bez = (k) => `cubic-bezier(${T.motion.easing[k].join(", ")})`;
const shadowCss = (layers) =>
  layers.length
    ? layers.map(([x, y, b, s, c]) => `${x}px ${y}px ${b}px ${s}px ${cssColor(resolve(c, DEFAULT_SCALE))}`).join(", ")
    : "none";
const gradientCss = (g, scale) =>
  `linear-gradient(${g.angle}deg, ${g.stops.map(([c, at]) => `${cssColor(resolve(c, scale))} ${at}%`).join(", ")})`;
const productVars = (p, ind) => {
  const pr = T.products[p];
  const [g0, g1] = gradStops(p);
  return [
    `${ind}--cp-p-accent: ${cssColor(resolve(pr.accent, pr.scale))};`,
    `${ind}--cp-p-accent-dark: ${cssColor(resolve(pr.accentDark, pr.scale))};`,
    `${ind}--cp-p-gradient-from: ${cssColor(g0)};`,
    `${ind}--cp-p-gradient-to: ${cssColor(g1)};`,
  ];
};
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

// ---------------------------------------------------------------- web: CSS
{
  const L = [`/* ${HEADER} */`, `/* Usage: <html data-cp-product="seller" data-theme="light|dark">. Defaults: consumer, OS theme. */`, ""];
  L.push(":root {");
  for (const [fam, steps] of Object.entries(T.palette))
    for (const [st, hex] of Object.entries(steps)) L.push(`  --cp-${fam}-${stepName(st)}: ${hex};`);
  L.push("", "  /* product scale — remapped per [data-cp-product] */");
  for (const st of productScaleSteps) L.push(`  --cp-p-${st}: var(--cp-${DEFAULT_SCALE}-${st});`);
  L.push(...productVars("consumer", "  "));
  L.push("", "  /* typography */");
  for (const k of Object.keys(T.font)) L.push(`  --cp-font-${k}: ${fontStack(k)};`);
  for (const [k, t] of Object.entries(T.type)) {
    const n = kebab(k);
    L.push(`  --cp-type-${n}: ${t.weight} ${t.size}px/${t.line}px var(--cp-font-${t.font});`);
    L.push(`  --cp-type-${n}-tracking: ${t.tracking}em;`);
  }
  L.push("", "  /* space, radius, size */");
  for (const [k, v] of Object.entries(T.space)) L.push(`  --cp-space-${stepName(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(T.radius)) L.push(`  --cp-radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(T.size)) L.push(`  --cp-size-${kebab(k)}: ${v}px;`);
  L.push("", "  /* elevation & effects */");
  for (const [k, v] of Object.entries(T.shadow)) L.push(`  --cp-shadow-${kebab(k)}: ${shadowCss(v)};`);
  L.push(`  --cp-gradient-brand: ${gradientCss(T.gradient.brand, DEFAULT_SCALE)};`);
  L.push(`  --cp-gradient-product: linear-gradient(${T.gradient.product.angle}deg, var(--cp-p-gradient-from) 0%, var(--cp-p-gradient-to) 100%);`);
  L.push(`  --cp-gradient-spark: ${gradientCss(T.gradient.spark, DEFAULT_SCALE)};`);
  const e = T.effect;
  L.push(`  --cp-glass-blur: ${e.glassBlur}px;`, `  --cp-disabled-opacity: ${e.disabledOpacity};`);
  L.push(`  --cp-pressed-scale: ${e.pressedScale};`, `  --cp-hover-overlay: ${e.hoverOverlay};`, `  --cp-pressed-overlay: ${e.pressedOverlay};`);
  L.push(`  --cp-focus-ring: 0 0 0 ${e.focusRingOffset}px var(--cp-color-surface), 0 0 0 ${e.focusRingOffset + e.focusRingWidth}px var(--cp-color-focus-ring);`);
  L.push("", "  /* motion */");
  for (const [k, v] of Object.entries(T.motion.duration)) L.push(`  --cp-duration-${k}: ${v}ms;`);
  for (const k of Object.keys(T.motion.easing)) L.push(`  --cp-ease-${k}: ${bez(k)};`);
  for (const [k, v] of Object.entries(T.zIndex)) L.push(`  --cp-z-${kebab(k)}: ${v};`);

  const semBlock = (mode, indent) => {
    const rows = [];
    for (const [k, v] of Object.entries(T.semantic[mode])) {
      const val = String(v).startsWith("&")
        ? `var(--cp-p-${kebab(v.slice(1))})`
        : String(v).startsWith("@")
        ? `var(--cp-p-${v.slice(1)})`
        : v.includes("/") || v.startsWith("#")
          ? cssColor(resolve(v, DEFAULT_SCALE))
          : `var(--cp-${v.replace(".", "-")})`;
      rows.push(`${indent}--cp-color-${kebab(k)}: ${val};`);
    }
    rows.push(`${indent}--cp-glass-tint: ${cssColor(resolve(T.effect[mode === "light" ? "glassTintLight" : "glassTintDark"]))};`);
    rows.push(`${indent}--cp-glass-border: ${cssColor(resolve(T.effect[mode === "light" ? "glassBorderLight" : "glassBorderDark"]))};`);
    rows.push(`${indent}color-scheme: ${mode};`);
    return rows;
  };
  L.push("", "  /* semantic — light */", ...semBlock("light", "  "), "}", "");
  for (const p of PRODUCTS) {
    const sc = T.products[p].scale;
    if (p === "consumer") continue;
    L.push(`:root[data-cp-product="${p}"] {`);
    for (const st of productScaleSteps) L.push(`  --cp-p-${st}: var(--cp-${sc}-${st});`);
    L.push(...productVars(p, "  "));
    L.push("}", "");
  }
  L.push("@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', ...semBlock("dark", "    "), "  }", "}", "");
  L.push(':root[data-theme="dark"] {', ...semBlock("dark", "  "), "}", "");
  L.push(
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    "    --cp-duration-moderate: 150ms;",
    "    --cp-duration-slow: 150ms;",
    "    --cp-duration-deliberate: 150ms;",
    "    --cp-pressed-scale: 1;",
    "  }",
    "}",
    "",
  );
  // utility classes for the type scale — opt-in, prefixed
  for (const [k, t] of Object.entries(T.type)) {
    const n = kebab(k);
    L.push(
      `.cp-${n} { font: var(--cp-type-${n}); letter-spacing: var(--cp-type-${n}-tracking);` +
        (t.upper ? " text-transform: uppercase;" : "") +
        (t.tabular ? " font-variant-numeric: tabular-nums;" : "") +
        " }",
    );
  }
  out("brand/dist/web/changepay-tokens.css", L.join("\n") + "\n");
}

